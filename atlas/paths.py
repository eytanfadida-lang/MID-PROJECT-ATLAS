from pathlib import Path

# עוגן יציב לשורש הפרויקט - לא תלוי בספריית העבודה (CWD) של מי שמריץ את הקוד.
# זה בדיוק מה שהיה חסר קודם: arbox_run_sync.py נאלץ לעשות os.chdir בעצמו כי כל
# שאר הקוד פותח קבצים לפי נתיב יחסי ל-CWD ולא לפי מיקום הפרויקט בפועל - עבד
# במקרה בפייתון-אנywhere רק כי ה-CWD שם תמיד זהה לתיקיית הפרויקט.
#
# parent.parent (לא parent!) כי הקובץ הזה יושב תחת atlas/ - שורש הפרויקט הוא
# ההורה של תיקיית atlas עצמה, לא התיקייה שבה נמצא הקובץ. פספוס הזה גרם לכל
# קובץ סוד ול-appointments.db להיפתח בטעות תחת atlas/ במקום בשורש האמיתי -
# ובגלל שהקוד "מרפא את עצמו" (יוצר secret/DB חדש וריק אם חסר), זה לא נראה
# כמו שגיאה בכלל, רק כאילו "אין נתונים" - התגלה רק בבדיקת webhook אמיתית
# עם טוקן אמיתי, לא בבדיקות טעינת עמודים סתם
PROJECT_ROOT = Path(__file__).resolve().parent.parent


def secret(name):
    """נתיב לקובץ סוד/טוקן/מצב מקומי בשורש הפרויקט (למשל '.flask_secret')."""
    return PROJECT_ROOT / name


def data(name):
    """נתיב לקובץ נתונים בשורש הפרויקט (למשל 'appointments.db')."""
    return PROJECT_ROOT / name
